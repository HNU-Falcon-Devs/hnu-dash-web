import { act, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { beforeEach, describe, expect, it, vi } from "vitest";
import { reconcileOffline, finalizeEvent, type OperationState } from "./actions";
import { OfflineForm } from "./offline-forms";

const { refresh } = vi.hoisted(() => ({ refresh: vi.fn() }));
vi.mock("next/navigation", () => ({ useRouter: () => ({ refresh }) }));
vi.mock("./actions", () => ({ reconcileOffline: vi.fn(), finalizeEvent: vi.fn() }));
const ORG = "11111111-1111-4111-8111-111111111111";
const EVENT = "22222222-2222-4222-8222-222222222222";
const TARGET = "33333333-3333-4333-8333-333333333333";
const scope = { organizationId: ORG, eventId: EVENT };
beforeEach(() => { vi.resetAllMocks(); });

describe("offline explicit, individual confirmation forms", () => {
  it("starts empty, rejects whitespace and resets decision/reason/confirmation on cancel", () => {
    render(<OfflineForm {...scope} kind="loss" targetId={TARGET} />);
    const form = screen.getByRole("form", { name: "Record session loss " + TARGET });
    const choice = within(form).getByRole("combobox");
    const why = within(form).getByRole("textbox");
    const checkbox = within(form).getByRole("checkbox");
    const submit = within(form).getByRole("button", { name: "Record session loss" });
    expect(choice).toHaveValue("");
    expect(submit).toBeDisabled();
    fireEvent.change(choice, { target: { value: "lost" } });
    fireEvent.change(why, { target: { value: " \n" } });
    fireEvent.click(checkbox);
    expect(submit).toBeDisabled();
    fireEvent.change(why, { target: { value: "Lost device" } });
    expect(checkbox).not.toBeChecked();
    fireEvent.click(checkbox);
    expect(submit).not.toBeDisabled();
    fireEvent.click(within(form).getByRole("button", { name: "Cancel confirmation" }));
    expect(choice).toHaveValue("");
    expect(why).toHaveValue("");
    expect(checkbox).not.toBeChecked();
    expect(reconcileOffline).not.toHaveBeenCalled();
  });
  it("has native keyboard-operable controls and keeps exact payload while pending and after response loss", async () => {
    let resolve!: (state: OperationState) => void;
    vi.mocked(reconcileOffline).mockImplementation(() => new Promise(done => { resolve = done; }));
    render(<OfflineForm {...scope} kind="review" targetId={TARGET} eligible preparationPage={2} claimPage={3} />);
    const form = screen.getByRole("form", { name: "Review offline claim " + TARGET });
    const choice = within(form).getByRole("combobox", { name: /Individual decision/ });
    const why = within(form).getByRole("textbox", { name: /Reason/ });
    const checkbox = within(form).getByRole("checkbox");
    choice.focus();
    expect(choice).toHaveFocus();
    fireEvent.change(choice, { target: { value: "approve" } });
    fireEvent.change(why, { target: { value: " exact reason " } });
    checkbox.focus();
    expect(checkbox).toHaveFocus();
    fireEvent.click(checkbox);
    fireEvent.submit(form);
    await waitFor(() => expect(within(form).getByRole("button", { name: "Submitting…" })).toBeDisabled());
    expect(why).toBeDisabled();
    expect(within(form).getByRole("button", { name: "Cancel confirmation" })).toBeDisabled();
    const payload = vi.mocked(reconcileOffline).mock.calls[0][1];
    expect(payload.get("choice")).toBe("approve");
    expect(payload.get("reason")).toBe(" exact reason ");
    expect(payload.get("target_id")).toBe(TARGET);
    expect(payload.get("claims_page")).toBe("3");
    await act(async () => resolve({ status: "error", message: "Unconfirmed. Reload.", reloadRequired: true }));
    expect(within(form).getByRole("alert")).toHaveTextContent("Unconfirmed");
    expect(why).toHaveValue(" exact reason ");
    expect(why).toBeDisabled();
    fireEvent.click(within(form).getByRole("button", { name: "Reload authoritative evidence" }));
    await waitFor(() => expect(refresh).toHaveBeenCalledTimes(1));
    expect(reconcileOffline).toHaveBeenCalledTimes(1);
    await waitFor(() => expect(why).not.toBeDisabled());
    expect(why).toHaveValue(" exact reason ");
    expect(checkbox).not.toBeChecked();
  });
  it("separates finalization from reconciliation and requires explicit confirmation", async () => {
    vi.mocked(finalizeEvent).mockResolvedValue({ status: "success", message: "Backend confirmed.", reloadRequired: true });
    render(<OfflineForm {...scope} kind="finalize" />);
    const form = screen.getByRole("form", { name: "Finalize offline attendance" });
    expect(within(form).getByRole("button", { name: "Finalize offline attendance" })).toBeDisabled();
    fireEvent.click(within(form).getByRole("checkbox"));
    fireEvent.submit(form);
    await waitFor(() => expect(finalizeEvent).toHaveBeenCalledTimes(1));
    expect(vi.mocked(finalizeEvent).mock.calls[0][1].get("confirm_offline_finalize")).toBe("yes");
    expect(reconcileOffline).not.toHaveBeenCalled();
    await waitFor(() => expect(within(form).getByText("Backend confirmed.")).toBeInTheDocument());
    expect(within(form).getByRole("button", { name: "Finalize offline attendance" })).toBeDisabled();
  });
});
